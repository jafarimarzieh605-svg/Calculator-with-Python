print("Calculator with Python.")

num_1 = int(input("Enter First Number: "))
num_2 = int(input("Enter Second Number: "))
action = input(" + - * / ")
if action == "+":
    print(num_1 + num_2)
if action == "-":
    print(num_1 - num_2)
if action == "*":
    print(num_1 * num_2)  
if action == "/":
    print(num_1 / num_2)
          